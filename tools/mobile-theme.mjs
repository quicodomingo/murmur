// Android's colour palette (Palette.kt) from the computer's tokens, app/src/murmur-theme.css: the
// same --mm-* names in camelCase, for the three themes in light and dark. Run it when the tokens change.
//   node tools/mobile-theme.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const root = new URL("../", import.meta.url).pathname;
const css = readFileSync(`${root}app/src/murmur-theme.css`, "utf8");
const outDir = `${root}mobile/android/app/src/main/kotlin/com/quicodomingo/murmur/ui`;

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
// #RGB, #RRGGBB, #RRGGBBAA (CSS order) or transparent → Compose's 0xAARRGGBB.
const argb = (v) => {
  if (v === "transparent") return "0x00000000";
  let h = v.replace("#", "");
  if (h.length === 3) h = [...h].map((c) => c + c).join("");
  const a = h.length === 8 ? h.slice(6) : "FF";
  return `0x${(a + h.slice(0, 6)).toUpperCase()}`;
};

const blocks = [...css.matchAll(/\[data-theme="(\w+)"\]\[data-mode="(\w+)"\]\s*\{([^}]*)\}/g)];
const palettes = blocks.map(([, theme, mode, body]) => ({
  name: `${theme}${mode[0].toUpperCase()}${mode.slice(1)}`,
  vars: [...body.matchAll(/--mm-([\w-]+):\s*([^;]+);/g)]
    .filter(([, , v]) => /^(#[0-9a-fA-F]{3,8}|transparent)$/.test(v.trim()))
    .map(([, k, v]) => [camel(k), argb(v.trim())]),
}));
const names = palettes[0].vars.map(([k]) => k);
for (const p of palettes) {
  const missing = names.filter((n) => !p.vars.some(([k]) => k === n));
  if (missing.length) throw new Error(`${p.name} lacks ${missing.join(", ")}`);
}

const kt = `// Generated by tools/mobile-theme.mjs from app/src/murmur-theme.css: don't edit, regenerate it.
package com.quicodomingo.murmur.ui

import androidx.compose.ui.graphics.Color

/** Murmur's colour tokens (the computer's --mm-*), for one theme in one mode. */
data class MurmurPalette(
${names.map((n) => `    val ${n}: Color,`).join("\n")}
) {
    companion object {
${palettes.map((p) => `        val ${p.name} = MurmurPalette(\n${p.vars.map(([k, v]) => `            ${k} = Color(${v}),`).join("\n")}\n        )`).join("\n")}
    }
}
`;
mkdirSync(outDir, { recursive: true });
writeFileSync(`${outDir}/Palette.kt`, kt);
console.log(`${palettes.length} palettes, ${names.length} tokens → ${outDir.replace(root, "")}/Palette.kt`);
