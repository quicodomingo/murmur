// The phone apps' texts come from the same place as the computer's: app/src/locales/<lang>/mobile.json
// (Catalan is the source; check-locales keeps the three in step). This writes the iOS String
// Catalog from them, with {{placeholders}} turned into %@ in the order they appear.
//   node tools/mobile-strings.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const LANGS = ["ca", "es", "en"];
const root = new URL("../", import.meta.url).pathname;
const out = `${root}mobile/ios/Murmur/Resources/Localizable.xcstrings`;

const flatten = (obj, prefix = "", acc = {}) => {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object") flatten(v, key, acc);
    else acc[key] = String(v);
  }
  return acc;
};
const toIOS = (s) => s.replace(/\{\{\s*[\w.]+\s*\}\}/g, "%@");

const byLang = Object.fromEntries(LANGS.map((l) => [l, flatten(JSON.parse(readFileSync(`${root}app/src/locales/${l}/mobile.json`, "utf8")))]));
const strings = {};
const plist = {};
for (const key of Object.keys(byLang.ca).sort()) {
  // android.*: only the Android app's (its notification channel).
  if (key.startsWith("android.")) continue;
  // infoPlist.<Key>: the system's own texts (the microphone permission), in InfoPlist.xcstrings.
  if (key.startsWith("infoPlist.")) {
    plist[key.slice(10)] = { extractionState: "manual", localizations: Object.fromEntries(LANGS.map((l) => [l, { stringUnit: { state: "translated", value: byLang[l][key] } }])) };
    continue;
  }
  strings[key] = {
    extractionState: "manual",
    localizations: Object.fromEntries(LANGS.map((l) => [l, { stringUnit: { state: "translated", value: toIOS(byLang[l][key] ?? byLang.ca[key]) } }])),
  };
}
writeFileSync(out, JSON.stringify({ sourceLanguage: "ca", strings, version: "1.0" }, null, 2) + "\n");
writeFileSync(out.replace("Localizable", "InfoPlist"), JSON.stringify({ sourceLanguage: "ca", strings: plist, version: "1.0" }, null, 2) + "\n");
console.log(`${Object.keys(strings).length} strings → ${out.replace(root, "")}`);

// Android: res/values*/strings.xml. English is the default (phones in any other language), with
// Catalan and Spanish beside it. Keys lose their dots ("home.empty" → "home_empty"), placeholders
// become %1$s, %2$s… and the iOS-only texts (infoPlist.*) stay out.
const androidRes = `${root}mobile/android/app/src/main/res`;
const toAndroidName = (key) => key.replace(/[^A-Za-z0-9_]/g, "_");
const PLACEHOLDER = /\{\{\s*[\w.]+\s*\}\}/g;
const toAndroid = (s) => {
  const hasArgs = /\{\{\s*[\w.]+\s*\}\}/.test(s);
  let n = 0;
  const value = s
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/\n/g, "\\n")
    .replace(/^([@?])/, "\\$1")
    // With placeholders a literal % is %%; without, aapt is told it isn't a format string.
    .replace(/%/g, hasArgs ? "%%" : "%")
    .replace(PLACEHOLDER, () => `%${++n}$s`);
  return { value, formatted: !hasArgs && s.includes("%") ? ' formatted="false"' : "" };
};
const androidKeys = Object.keys(byLang.ca).filter((k) => !k.startsWith("infoPlist.")).sort();
for (const [lang, dir] of [["en", "values"], ["ca", "values-ca"], ["es", "values-es"]]) {
  const lines = androidKeys.map((k) => {
    const { value, formatted } = toAndroid(byLang[lang][k] ?? byLang.ca[k]);
    return `    <string name="${toAndroidName(k)}"${formatted}>${value}</string>`;
  });
  mkdirSync(`${androidRes}/${dir}`, { recursive: true });
  writeFileSync(`${androidRes}/${dir}/strings.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/mobile-strings.mjs from app/src/locales/${lang}/mobile.json: don't edit. -->\n<resources>\n${lines.join("\n")}\n</resources>\n`);
}
console.log(`${androidKeys.length} strings → ${androidRes.replace(root, "")}/values*/strings.xml`);
